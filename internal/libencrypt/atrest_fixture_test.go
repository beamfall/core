// Byte-exact immutable format fixtures (TECHDUR-CORE-CRYPTO-1 acceptance).
// The committed files in testdata/ pin the v1 and v2 wire formats forever: any
// codec drift — header layout, frame framing, key derivation, AAD, nonce
// schedule — breaks these tests. NEVER regenerate the fixtures; a change that
// needs new fixtures is a new format version.
//
// Both fixtures encrypt the same deterministic 100000-byte plaintext
// (b[i] = (i*131+89) % 251) under DEK = 0x00..0x1f. The v2 fixture uses
// salt = 0x20..0x3f and the fixture ObjectContext; the v1 fixture was minted
// once (v1 nonces are random) and is pinned by content hash.

const (
	// Full SHA-256 of the committed fixture files — immutability pins.
	v1FixtureSHA256 = "9b4790603b6a8d8c01a23bf783c266278c723ba84751044b0ee8aa301b432ae7"
	v2FixtureSHA256 = "699b2405825283a4d5c265e826c6400df13e8651c9204c06a6a6dc7ce736ec6f"
)

func fixtureBytes(t *testing.T, name, wantSHA string) []byte {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join("testdata", name)) //nolint:gosec // fixed committed fixture name
	if err != nil {
		t.Fatalf("read fixture: %v", err)
	}
	sum := sha256.Sum256(raw)
	if hex.EncodeToString(sum[:]) != wantSHA {
		t.Fatalf("fixture %s content hash changed — the committed format fixture is immutable", name)
	}
	return raw
}

func fixtureSalt() []byte {
	salt := make([]byte, atRestV2SaltLen)
	for i := range salt {
		salt[i] = byte(0x20 + i)
	}
	return salt
}

// TestV2FixtureByteExact regenerates the v2 fixture deterministically (fixed
// DEK, salt, context — v2 nonces are the frame counter) and demands identity
// with the committed bytes, then pins header, frame offsets, and AAD bytes.
func TestV2FixtureByteExact(t *testing.T) {
	fixture := fixtureBytes(t, "atrest_v2_fixture.bin", v2FixtureSHA256)
	dek := v2TestDEK()
	obj := v2TestObj()
	plain := v2TestPlain(100000)

	var regenerated bytes.Buffer
	if err := encryptStreamV2WithSalt(&regenerated, bytes.NewReader(plain), dek, obj, fixtureSalt()); err != nil {
		t.Fatalf("regenerate: %v", err)
	}
	if !bytes.Equal(regenerated.Bytes(), fixture) {
		t.Fatal("v2 codec no longer reproduces the committed fixture byte-for-byte")
	}

	// Header bytes: BFE2 || 0x02 || u32be(65536) || salt[32].
	wantHeader := append([]byte("BFE2"), 0x02, 0x00, 0x01, 0x00, 0x00)
	wantHeader = append(wantHeader, fixtureSalt()...)
	if !bytes.Equal(fixture[:atRestV2HeaderLen], wantHeader) {
		t.Fatalf("fixture header = %x, want %x", fixture[:atRestV2HeaderLen], wantHeader)
	}

	// Frame offsets: full frame at 41 (len u32be(65552)), final short frame at
	// 41+4+65552 with len 34464+16, then EOF.
	frame0Len := binary.BigEndian.Uint32(fixture[41:45])
	if frame0Len != atRestV2ChunkSize+atRestV2TagLen {
		t.Fatalf("frame 0 length = %d, want %d", frame0Len, atRestV2ChunkSize+atRestV2TagLen)
	}
	finalOffset := 41 + 4 + int(frame0Len)
	finalLen := binary.BigEndian.Uint32(fixture[finalOffset : finalOffset+4])
	if want := uint32(100000 - atRestV2ChunkSize + atRestV2TagLen); finalLen != want {
		t.Fatalf("final frame length = %d, want %d", finalLen, want)
	}
	if len(fixture) != finalOffset+4+int(finalLen) {
		t.Fatalf("fixture size = %d, want exactly header+2 frames", len(fixture))
	}

	// AAD bytes: raw-header || context || u32be(index) || final-byte.
	context, err := obj.encode()
	if err != nil {
		t.Fatal(err)
	}
	aadPrefix := append(append([]byte{}, wantHeader...), context...)
	aad1 := v2AAD(aadPrefix, 1, true)
	wantTail := []byte{0x00, 0x00, 0x00, 0x01, 0x01}
	if !bytes.HasPrefix(aad1, aadPrefix) || !bytes.HasSuffix(aad1, wantTail) {
		t.Fatal("final-frame AAD bytes drifted from the pinned layout")
	}
	// The pinned AAD is the one the AEAD actually verifies: opening frame 1
	// with exactly this AAD succeeds, and with a flipped final byte fails.
	gcm, err := newV2GCM(dek, fixtureSalt(), context)
	if err != nil {
		t.Fatal(err)
	}
	frame1 := fixture[finalOffset+4:]
	if _, err := gcm.Open(nil, v2Nonce(1), frame1, aad1); err != nil {
		t.Fatalf("pinned AAD failed to authenticate the fixture's final frame: %v", err)
	}
	if _, err := gcm.Open(nil, v2Nonce(1), frame1, v2AAD(aadPrefix, 1, false)); err == nil {
		t.Fatal("final frame authenticated with non-final AAD")
	}

	// And the fixture decrypts to the exact plaintext through both decoders.
	got, err := decryptV2Both(t, fixture, dek, obj)
	if err != nil || !bytes.Equal(got, plain) {
		t.Fatalf("fixture decrypt: %v", err)
	}
}

// TestV1FixtureImmutable pins the legacy v1 format: committed header/offset
// layout and byte-exact decrypt under the fixed DEK. Persisted v1 objects must
// keep decrypting in v1 key generations forever.
func TestV1FixtureImmutable(t *testing.T) {
	fixture := fixtureBytes(t, "atrest_v1_fixture.bin", v1FixtureSHA256)
	dek := v2TestDEK()
	plain := v2TestPlain(100000)

	// Header bytes: BFE1 || 0x01 || u32be(65536).
	wantHeader := append([]byte("BFE1"), 0x01, 0x00, 0x01, 0x00, 0x00)
	if !bytes.Equal(fixture[:atRestHeaderLen], wantHeader) {
		t.Fatalf("v1 fixture header = %x, want %x", fixture[:atRestHeaderLen], wantHeader)
	}
	// Frame offset layout: len(4) || nonce(12) || ct+tag; frame 0 sealed len is
	// nonce + chunk + tag.
	frame0Len := binary.BigEndian.Uint32(fixture[atRestHeaderLen : atRestHeaderLen+4])
	if want := uint32(gcmNonceLen + atRestChunkSize + 16); frame0Len != want {
		t.Fatalf("v1 frame 0 sealed length = %d, want %d", frame0Len, want)
	}

	var out bytes.Buffer
	if err := DecryptStream(&out, bytes.NewReader(fixture), dek); err != nil {
		t.Fatalf("v1 fixture DecryptStream: %v", err)
	}
	if !bytes.Equal(out.Bytes(), plain) {
		t.Fatal("v1 fixture plaintext mismatch")
	}
	// Seekable v1 reader still serves ranges over the fixture.
	reader, err := NewDecryptReader(bytes.NewReader(fixture), int64(len(fixture)), dek)
	if err != nil {
		t.Fatalf("NewDecryptReader: %v", err)
	}
	if _, err := reader.Seek(70000, io.SeekStart); err != nil {
		t.Fatal(err)
	}
	buf := make([]byte, 8)
	if _, err := io.ReadFull(reader, buf); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(buf, plain[70000:70008]) {
		t.Fatal("v1 fixture range read mismatch")
	}
	// A truncated fixture still fails closed.
	var discard bytes.Buffer
	if err := DecryptStream(&discard, bytes.NewReader(fixture[:len(fixture)-1]), dek); !errors.Is(err, ErrUnwrap) {
		t.Fatalf("truncated v1 fixture: err = %v, want ErrUnwrap", err)
	}
}
