import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import type { Plugin } from "vite";

const CACHE_PREFIX = "beamfall-shell-";

type ShellAsset = {
  fileName: string;
  source: string | Uint8Array;
};

// beamfall-sw: emits a hand-written, shell-only service worker (ADR-0007 §1)
// into the build output. We avoid vite-plugin-pwa/Workbox on purpose — the
// requirement is narrow (precache the app shell, NEVER touch /api or media),
// and a ~40-line worker keeps the caching contract auditable in one file with
// the /api exclusion explicit rather than buried in generated runtime config.
//
// The worker is generated rather than shipped static because it must precache
// the *content-hashed* shell filenames, which only exist after the bundle is
// built. We read them from the rollup bundle in generateBundle and inline the
// list into the worker source.

export function beamfallShellSW(options: { base: string }): Plugin {
  const base = options.base; // "/web/"
  let publicDir = "";
  // Static assets copied verbatim from public/ (not part of the rollup bundle).
  const publicShell = [
    "manifest.webmanifest",
    "favicon.png",
    "favicon.svg",
    "apple-touch-icon.png",
    "manifest-icon-192.png",
    "manifest-icon-512.png",
    "manifest-icon.svg",
  ];

  return {
    name: "beamfall-sw",
    apply: "build",
    enforce: "post",
    configResolved(config) {
      publicDir = config.publicDir;
    },
    generateBundle(_outputOptions, bundle) {
      // Collect the entry shell only: index.html, the entry chunk, its static
      // imports, and their CSS. Lazy route chunks stay network/on-demand.
      const shell = new Set<string>();
      shell.add("index.html");
      const addChunk = (fileName: string) => {
        if (shell.has(fileName)) return;
        const item = bundle[fileName];
        if (!item || item.type !== "chunk") return;
        shell.add(fileName);
        for (const file of item.imports) addChunk(file);
        const metadata = item.viteMetadata as { importedCss?: Set<string> } | undefined;
        for (const file of metadata?.importedCss ?? []) shell.add(file);
      };
      for (const item of Object.values(bundle)) {
        if (item.type === "chunk" && item.isEntry) addChunk(item.fileName);
      }
      for (const f of publicShell) shell.add(f);

      const sorted = [...shell].sort();
      const assets = sorted.map((fileName): ShellAsset => {
        const item = bundle[fileName];
        if (item?.type === "chunk") return { fileName, source: item.code };
        if (item?.type === "asset") return { fileName, source: item.source };
        return { fileName, source: readFileSync(join(publicDir, fileName)) };
      });

      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: renderShellServiceWorker(base, assets),
      });
    },
  };
}

export function renderShellServiceWorker(base: string, assets: readonly ShellAsset[]): string {
  const sorted = [...assets].sort((a, b) => a.fileName.localeCompare(b.fileName));
  const version = contentVersion(sorted);
  const precacheURLs = sorted.map(({ fileName }) => JSON.stringify(base + fileName)).join(",\n  ");

  return `/* Beamfall app-shell service worker (generated by sw-plugin.ts).
 * ADR-0007 §1: PWA = manifest + a service worker caching the SHELL ONLY.
 * Offline media is explicitly out of scope (post-parity "offline packs").
 *
 * Caching contract:
 *   - Precache the content-hashed entry shell (JS/CSS/index + manifest + icons).
 *   - Serve the hashed assets cache-first (a new build gets new hashes).
 *   - Navigations are NETWORK-FIRST: the server's current index.html wins, so
 *     the first load after a binary upgrade references chunks the new server
 *     has, and the precached shell is only the offline fallback (SPA deep
 *     links offline).
 *   - EVERYTHING ELSE — and /api/* in particular — bypasses the cache entirely
 *     (network passthrough, never read from or written to the cache), so the
 *     worker can NEVER serve stale library, playback, or media data.
 */
const CACHE_PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const CACHE = CACHE_PREFIX + ${JSON.stringify(version)};
const BASE = ${JSON.stringify(base)};
const SHELL_URL = ${JSON.stringify(base + "index.html")};
const PRECACHE = [
  ${precacheURLs}
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys
          .filter((k) => k.startsWith(CACHE_PREFIX) && k !== CACHE)
          .map((k) => caches.delete(k))
      )
    ).then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return; // never touch mutations
  const url = new URL(req.url);

  // Same-origin only; cross-origin requests pass through untouched.
  if (url.origin !== self.location.origin) return;

  // HARD EXCLUSION: API and media. /api/* carries GraphQL, the manifest, SSE,
  // and Stream-Token media bytes — caching any of it would serve stale library
  // or playback data. Let these hit the network directly, no cache involvement.
  if (url.pathname.startsWith("/api/")) return;

  // Only the shell namespace (/web/) is ours to serve.
  if (!url.pathname.startsWith(BASE)) return;

  // App navigations: network-first. The server's index.html is the only copy
  // whose chunk hashes match what the server can serve, so a cached shell
  // is used ONLY when the network is unreachable (deep links offline); the
  // SPA router resolves the route client-side either way.
  if (req.mode === "navigate") {
    event.respondWith(
      fetch(req).catch(() => caches.match(SHELL_URL).then((cached) => cached || Response.error()))
    );
    return;
  }

  // Hashed shell assets: cache-first (immutable — a new build gets new hashes).
  event.respondWith(
    caches.match(req).then((cached) => cached || fetch(req))
  );
});
`;
}

function contentVersion(assets: readonly ShellAsset[]): string {
  const digest = createHash("sha256");
  for (const { fileName, source } of assets) {
    digest.update(fileName);
    digest.update("\0");
    digest.update(source);
    digest.update("\0");
  }
  return digest.digest("hex").slice(0, 16);
}
