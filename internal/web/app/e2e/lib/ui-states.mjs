// The inventory of every web UI state, and the reviewed list of the ones no test covers yet
// (CORE-1305). require-ui-state-coverage.mjs joins it to the smoke run and fails on any row that
// is neither covered nor listed in UI_STATE_GAPS.
//
// A row is covered when a passing test declares its id with coverUiStates() (ui-state-coverage.ts),
// or when the row names a visual-parity golden and that golden's comparison passed.
//
// Row ids:
//   <screen>                       the screen renders at desktop width, en-US, as its owner
//   <screen>#<kind>:<name>         an in-page state: dialog, menu, tab, select, empty, error, loading
//   <screen>@mobile                the screen at phone width
//   <screen>@large-text            the screen with 200% text
//   <screen>@forced-colors         the screen in forced-colors mode
//   area:<area>@role:<role>        an area as one role
//   area:<area>@locale:<locale>    an area in a non-English locale
//
// Role and locale are inventoried per area, not per screen, because that is where the code
// decides them. Role gates sit at the area root (RequireRole in App.tsx, the AdminGate around
// every Console route), and each area loads one string catalog. Breakpoint and a11y variants are
// per screen, because each screen lays itself out.
//
// <screen> is the route as it appears in the router, so the unit test can compare these lists
// with App.tsx and the area routers.

