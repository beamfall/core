function screenRows() {
  return SCREENS.flatMap((screen) => [
    { id: screen, screen, kind: "screen" },
    ...(IN_PAGE_STATES[screen] ?? []).map((state) => ({
      id: `${screen}#${state.kind}:${state.name}`,
      screen,
      kind: state.kind,
      ...(state.visualParity ? { visualParity: state.visualParity } : {}),
    })),
    ...SCREEN_VARIANTS.map((variant) => ({
      id: `${screen}@${variant}`,
      screen,
      kind: variant === "mobile" ? "breakpoint" : "a11y",
    })),
  ]);
}

