#!/usr/bin/env python3
from __future__ import annotations

import importlib.util
import json
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest import mock


ROOT = Path(__file__).resolve().parent.parent
FUZZ_ONE_SPEC = importlib.util.spec_from_file_location("fuzz_one_tested", ROOT / "script/fuzz-one.py")
assert FUZZ_ONE_SPEC and FUZZ_ONE_SPEC.loader
FUZZ_ONE = importlib.util.module_from_spec(FUZZ_ONE_SPEC)
FUZZ_ONE_SPEC.loader.exec_module(FUZZ_ONE)


def target(name: str, *, tags: list[str] | None = None, goos: list[str] | None = None, goarch: list[str] | None = None) -> dict[str, object]:
    return {
        "pkg": "./internal/example",
        "target": name,
        "tags": tags or [],
        "goos": goos or [],
        "goarch": goarch or [],
    }


class FuzzManifestTest(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        (self.root / "testing").mkdir()
        package = self.root / "internal/example"
        (package / "testdata/fuzz/FuzzOne").mkdir(parents=True)
        (package / "testdata/fuzz/FuzzOne/seed0").write_text("seed\n", encoding="utf-8")
        (package / "example_fuzz_test.go").write_text(
            'package example\nimport "testing"\nfunc FuzzOne(f *testing.F) {}\n', encoding="utf-8"
        )
        self.write_manifest([target("FuzzOne")])

    def tearDown(self) -> None:
        self.temp.cleanup()

    def write_manifest(self, targets: list[dict[str, object]], mappings: list[dict[str, object]] | None = None) -> None:
        payload = {
            "version": 1,
            "discovery": {
                "roots": ["."],
                "exclude_dirs": [".git", "node_modules"],
                "generated": "exclude",
                "tag_mappings": mappings or [],
            },
            "targets": targets,
        }
        (self.root / "testing/fuzz-targets.json").write_text(json.dumps(payload), encoding="utf-8")

    def invoke(self, mode: str = "validate") -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            ["go", "run", "./tools/fuzzmanifest", "-root", str(self.root), "-mode", mode],
            cwd=ROOT,
            text=True,
            capture_output=True,
        )

    def test_matrix_and_drift_cases(self) -> None:
        result = self.invoke("matrix")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(json.loads(result.stdout), {"include": [target("FuzzOne")]})

        source = self.root / "internal/example/example_fuzz_test.go"
        source.write_text(source.read_text() + "func FuzzTwo(f *testing.F) {}\n", encoding="utf-8")
        self.assertIn("unmanifested fuzz target", self.invoke().stderr)

        source.write_text('package example\nimport "testing"\nfunc FuzzRenamed(f *testing.F) {}\n', encoding="utf-8")
        renamed = self.invoke()
        self.assertIn("missing fuzz target", renamed.stderr)
        self.assertIn("unmanifested fuzz target", renamed.stderr)

        self.write_manifest([target("FuzzExtra")])
        self.assertIn("missing or empty fuzz seed corpus", self.invoke().stderr)

    def test_tags_generated_and_corpus_contracts(self) -> None:
        source = self.root / "internal/example/example_fuzz_test.go"
        source.write_text(
            '//go:build special\n\npackage example\nimport "testing"\nfunc FuzzOne(f *testing.F) {}\n', encoding="utf-8"
        )
        mismatch = self.invoke()
        self.assertIn("unmapped build expression", mismatch.stderr)
        self.write_manifest(
            [target("FuzzOne", tags=["special"])],
            [{"expression": "special", "tags": ["special"]}],
        )
        self.assertEqual(self.invoke().returncode, 0)

        generated = self.root / "internal/example/generated_fuzz_test.go"
        generated.write_text(
            '// Code generated by fixture; DO NOT EDIT.\npackage example\nimport "testing"\nfunc FuzzGenerated(f *testing.F) {}\n', encoding="utf-8"
        )
        self.assertEqual(self.invoke().returncode, 0)

        (self.root / "internal/example/testdata/fuzz/Misspelled").mkdir()
        (self.root / "internal/example/testdata/fuzz/Misspelled/seed0").write_text("x")
        self.assertIn("orphan fuzz seed corpus", self.invoke().stderr)

    def test_compound_expression_runs_native_without_reserved_tags_and_skips_other_hosts(self) -> None:
        source = self.root / "internal/example/example_fuzz_test.go"
        source.write_text(
            '//go:build linux || darwin\n\npackage example\nimport "testing"\nfunc FuzzOne(f *testing.F) {}\n',
            encoding="utf-8",
        )
        self.assertIn("unmapped build expression", self.invoke().stderr)
        self.write_manifest(
            [target("FuzzOne", goos=["linux", "darwin"])],
            [{"expression": "linux || darwin", "goos": ["linux", "darwin"]}],
        )
        result = self.invoke("matrix")
        self.assertEqual(result.returncode, 0, result.stderr)
        matrix_target = json.loads(result.stdout)["include"][0]
        self.assertEqual(matrix_target["tags"], [])
        self.assertEqual(matrix_target["goos"], ["linux", "darwin"])
        self.assertNotIn("linux || darwin", result.stdout)

        with mock.patch.object(FUZZ_ONE.subprocess, "run") as run:
            self.assertTrue(
                FUZZ_ONE.run_one(
                    ROOT,
                    "./internal/example",
                    "FuzzOne",
                    [],
                    ["linux", "darwin"],
                    [],
                    "5m",
                    active=True,
                    native=("darwin", "arm64"),
                )
            )
        argv = run.call_args.args[0]
        self.assertNotIn("-tags", argv)
        with mock.patch.object(FUZZ_ONE.subprocess, "run") as run:
            self.assertFalse(
                FUZZ_ONE.run_one(
                    ROOT,
                    "./internal/example",
                    "FuzzOne",
                    [],
                    ["linux", "darwin"],
                    [],
                    "5m",
                    active=True,
                    native=("windows", "amd64"),
                )
            )
            run.assert_not_called()

    def test_reserved_platform_tags_are_rejected_cross_platform(self) -> None:
        source = self.root / "internal/example/example_fuzz_test.go"
        source.write_text(
            '//go:build linux\n\npackage example\nimport "testing"\nfunc FuzzOne(f *testing.F) {}\n',
            encoding="utf-8",
        )
        for reserved in ("linux", "windows", "amd64", "arm64"):
            self.write_manifest(
                [target("FuzzOne", tags=[reserved])],
                [{"expression": "linux", "tags": [reserved]}],
            )
            self.assertIn("invalid or duplicate mapped build tag", self.invoke().stderr)
        with self.assertRaisesRegex(ValueError, "invalid fuzz tags"):
            FUZZ_ONE.validated("./internal/example", "FuzzOne", ["windows"], [], [], "5m")

        self.write_manifest(
            [],
            [{"expression": "linux", "exclude": True, "reason": "not runnable in CI"}],
        )
        self.assertEqual(json.loads(self.invoke("matrix").stdout), {"include": []})

    def test_repository_wiring_uses_one_manifest(self) -> None:
        workflow = (ROOT / ".github/workflows/fuzz-nightly.yml").read_text(encoding="utf-8")
        runner = (ROOT / "script/fuzz-run.py").read_text(encoding="utf-8")
        self.assertIn("fromJSON(needs.manifest.outputs.matrix)", workflow)
        self.assertIn("FUZZ_TAGS_JSON: ${{ toJSON(matrix.tags) }}", workflow)
        self.assertIn("FUZZ_GOOS_JSON: ${{ toJSON(matrix.goos) }}", workflow)
        self.assertIn("FUZZ_GOARCH_JSON: ${{ toJSON(matrix.goarch) }}", workflow)
        self.assertIn("run: python3 script/fuzz-one.py --duration 5m", workflow)
        self.assertNotIn("-fuzz=${{ matrix.target }}", workflow)
        self.assertIn("./tools/fuzzmanifest", runner)
        self.assertIn("fuzz-one.py", runner)
        self.assertIn("fuzz-run.py\" seed", (ROOT / "script/fuzz-seed.sh").read_text())
        self.assertIn("fuzz-run.py\" active", (ROOT / "script/fuzz-smoke.sh").read_text())


if __name__ == "__main__":
    unittest.main()
