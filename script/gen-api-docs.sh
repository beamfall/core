#!/usr/bin/env sh
# Regenerate the /v1 developer-API doc set from docs/api/openapi.json:
#
#   docs/api/reference.md   — rendered Markdown reference (openapi_to_md.py)
#   docs/api/llms.txt       — LLM index (llmstxt.org layout)
#   docs/api/llms-full.txt  — full LLM corpus (reference + raw spec)
#
# The OpenAPI spec is the source of truth (internal/server/v1_test.go pins it
# against the live handlers). Run after any spec change: script/gen-api-docs.sh
set -eu
SCRIPT_ROOT=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
SOURCE_ROOT=$SCRIPT_ROOT
OUTPUT_ROOT=$SCRIPT_ROOT
while [ "$#" -gt 0 ]; do
  case "$1" in
    --source-root) SOURCE_ROOT=$2; shift 2 ;;
    --output-root) OUTPUT_ROOT=$2; shift 2 ;;
    *) echo "usage: $0 [--source-root DIR] [--output-root DIR]" >&2; exit 2 ;;
  esac
done

SPEC=$SOURCE_ROOT/docs/api/openapi.json
OUT=$OUTPUT_ROOT/docs/api
mkdir -p "$OUT"
VERSION=$(python3 -c "import json;print(json.load(open('$SPEC'))['info']['version'])")

python3 "$SCRIPT_ROOT/script/openapi_to_md.py" "$SPEC" > "$OUT/reference.md"

cat > "$OUT/llms.txt" <<EOF
# Beamfall Developer API

> The Beamfall \`/v1/\` stable developer contract (ADR-0040), version $VERSION.
> Scoped bearer keys (\`Authorization: Bearer bfk_...\`), Reveal-filtered and
> Profile-bound reads, no breaking changes within a major version. The wire
> entity is \`Media\`; the surface is domain-agnostic. Regenerated by
> script/gen-api-docs.sh — do not edit by hand.

## Docs

- [API reference](reference.md): every /v1 endpoint, auth, scopes, and schemas (rendered from the OpenAPI spec)
- [OpenAPI spec](openapi.json): the machine-readable source of truth, pinned against the handlers by internal/server/v1_test.go
- [Home-automation guide](home-automation.md): event stream and playback-control integration notes
EOF

{
  printf '# Beamfall Developer API — full documentation corpus (v%s)\n' "$VERSION"
  printf '# Generated by script/gen-api-docs.sh — do not edit by hand.\n\n'
  printf '\n---\nsource: docs/api/reference.md\n---\n\n'
  cat "$OUT/reference.md"
  printf '\n---\nsource: docs/api/home-automation.md\n---\n\n'
  cat "$SOURCE_ROOT/docs/api/home-automation.md"
  printf '\n---\nsource: docs/api/openapi.json\n---\n\n'
  cat "$SPEC"
} > "$OUT/llms-full.txt"

echo "gen-api-docs: wrote $OUT/reference.md $OUT/llms.txt $OUT/llms-full.txt"
